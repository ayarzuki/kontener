ALIAS = {"–": "-", "—": "-", "…": "."}
GL = {k: np.array([[c == "#" for c in row] for row in v], bool) for k, v in GLYPHS.items()}


def text_width(s, scale=1):
    return (len(s) * 6 - 1) * scale


def draw_text(arr, x, y, s, color, scale=1, shadow=None):
    """Tulis teks ke array HxWx3 (uint8) di (x, y) kiri-atas."""
    s = "".join(ALIAS.get(ch, ch) for ch in s).upper()
    if shadow is not None:
        draw_text(arr, x + scale, y + scale, s, shadow, scale)
    cx = x
    H, W = arr.shape[:2]
    for ch in s:
        g = GL.get(ch, GL["?"])
        if scale > 1:
            g = np.kron(g, np.ones((scale, scale), bool))
        gh, gw = g.shape
        x0, y0 = int(cx), int(y)
        xa, ya, xb, yb = max(0, x0), max(0, y0), min(W, x0 + gw), min(H, y0 + gh)
        if xb > xa and yb > ya:
            sub = g[ya - y0:yb - y0, xa - x0:xb - x0]
            arr[ya:yb, xa:xb][sub] = color
        cx += 6 * scale


def draw_text_c(arr, cx, y, s, color, scale=1, shadow=None):
    draw_text(arr, int(cx - text_width(s, scale) / 2), y, s, color, scale, shadow)


BAYER = np.array([[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]], np.float32) / 16 + 1 / 32


def dither_gradient(h, w, colors, axis=0, x0=0, y0=0):
    """Gradien antara beberapa warna dengan dithering Bayer 4x4 (khas pixel art)."""
    cols = np.asarray(colors, np.float32)
    n = len(cols) - 1
    if axis == 0:
        t = np.linspace(0, 1, h, dtype=np.float32)[:, None].repeat(w, 1)
    else:
        t = np.linspace(0, 1, w, dtype=np.float32)[None, :].repeat(h, 0)
    yy, xx = np.mgrid[y0:y0 + h, x0:x0 + w]
    thr = BAYER[yy % 4, xx % 4]
    pos = t * n
    i = np.clip(pos.astype(int), 0, n - 1)
    f = pos - i
    pick = np.where(f > thr, i + 1, i)
    return cols[pick].astype(np.uint8)


def light_mask(h, w, cx, cy, r, levels=3, x0=0, y0=0):
    """Kolam cahaya bertingkat (banding) + dither di tepinya."""
    yy, xx = np.mgrid[y0:y0 + h, x0:x0 + w]
    d = np.hypot(xx - cx, (yy - cy) * 1.1) / r
    v = np.clip(1 - d, 0, 1) * levels
    thr = BAYER[yy % 4, xx % 4]
    return (np.floor(v) + (v - np.floor(v) > thr)) / levels


def rect(arr, x0, y0, x1, y1, color):
    H, W = arr.shape[:2]
    xa, ya, xb, yb = max(0, int(x0)), max(0, int(y0)), min(W, int(x1)), min(H, int(y1))
    if xb > xa and yb > ya:
        arr[ya:yb, xa:xb] = color


def poly(img, pts, color):
    ImageDraw.Draw(img).polygon(pts, fill=tuple(int(c) for c in color))


def to_img(arr):
    return Image.fromarray(arr)
